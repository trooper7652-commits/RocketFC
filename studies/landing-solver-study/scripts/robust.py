"""Pre-registered robustness gate (notes/03_metrics.md): finalist vs the table
under the SAME model mismatch, seeds 101-103 x 200.

Belief mismatch (the plant stays nominal; the flight software believes a wrong
value): a fresh copy of ws_base gets burn_table.h regenerated by the repo's
own tools/burn_table.py with the wrong value, and a fresh copy of ws_cand gets
landing_table.h regenerated with it; both flight DLLs also get the wrong
config.h constant. Plant mismatch: --plant knobs, solvers nominal.
"""
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
L = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import metrics as M  # noqa: E402

PY = sys.executable
SEEDS = ["101", "102", "103"]
DL = os.path.join(L, "downloads")
CAND_GEN = ["--eh-mean", "-0.01", "--eh-sd", "0.03", "--ev-mean", "0.02", "--ev-sd", "0.035"]

BELIEF = [  # name, config constant, value, burn_table.py args, landing_table.py args
    ("mass_x0.9", "MASS_DESCENT_KG", 0.855, ["--mass", "0.855"]),
    ("mass_x1.1", "MASS_DESCENT_KG", 1.045, ["--mass", "1.045"]),
    ("cda_x0.7", "CDA_M2", 0.0028, ["--cda", "0.0028"]),
    ("cda_x1.3", "CDA_M2", 0.0052, ["--cda", "0.0052"]),
    ("delay_425", "IGNITION_DELAY_MS", 425.0, ["--delay-ms", "425"]),
    ("delay_575", "IGNITION_DELAY_MS", 575.0, ["--delay-ms", "575"]),
]
PLANT = [  # name, --plant k=v list
    ("thrust_x0.9", ["landing_thrust_scale=0.9"]),
    ("thrust_x1.1", ["landing_thrust_scale=1.1"]),
    ("curve_coker", ["landing_eng_path=" + json.dumps(os.path.join(DL, "tc_cert_coker", "data.eng"))]),
    ("curve_smart", ["landing_eng_path=" + json.dumps(os.path.join(DL, "tc_cert_smart", "data.eng"))]),
    ("baro_lag_0", ["baro_lag_s=0.0"]),
    ("baro_lag_10", ["baro_lag_s=0.010"]),
    ("baro_lag_50", ["baro_lag_s=0.050"]),
    ("baro_lag_75", ["baro_lag_s=0.075"]),
    ("baro_q_+0.1", ["baro_q_coeff=0.1"]),
    ("baro_q_-0.1", ["baro_q_coeff=-0.1"]),
    ("accel_bias_20mg", ["accel_bias_mps2=[0.196,0.196,0.196]"]),
]


def copy_ws(src, dst):
    if os.path.exists(dst):
        return dst
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("build", "__pycache__", "*.dll", "replay.exe", "cases"))
    return dst


def mc(ws, out, fw=None, plant=None):
    if os.path.exists(out):
        return M.load(out)
    cmd = [PY, os.path.join(HERE, "mc.py"), "--ws", ws, "--seeds", *SEEDS, "--n", "200", "--out", out]
    if fw:
        cmd += ["--fw-overrides", json.dumps(fw)]
    if plant:
        cmd += ["--plant", *plant]
    subprocess.run(cmd, check=True)
    return M.load(out)


def verdict(b, c):
    sb, sc = M.stats(b), M.stats(c)
    p = M.paired(b, c)
    ab_ok = all(sc["aborts"].get(k, 0) <= sb["aborts"].get(k, 0) + 2
                for k in set(sb["aborts"]) | set(sc["aborts"]))
    ok = (p["d_median"] <= 0.10 and p["d_p90"] <= 0.25 and sc["hops"] <= sb["hops"] + 2 and ab_ok)
    return ok, sb, sc, p


SPECS = {  # name -> (candidate workspace, landing_table.py extra args)
    "track1": ("ws_cand", CAND_GEN),
    "track2": ("ws_cand", CAND_GEN),
    "d2only": ("ws_nomtab", ["--delay-pct", "0", "--mass-pct", "0", "--cda-pct", "0",
                             "--thrust-sd-pct", "0", "--eh-sd", "0", "--ev-sd", "0",
                             "--draws", "4"]),
}


def main():
    finalist = sys.argv[1]  # track1 | track2 | d2only
    fw_cand = json.load(open(os.path.join(L, "data", f"finalist_{finalist}.json")))
    cws, cgen = SPECS[finalist]
    rows = []
    for name, const, val, args in BELIEF:
        wb = copy_ws(os.path.join(L, "ws_base", "RocketFC"), os.path.join(L, f"rb_base_{name}", "RocketFC"))
        wc = copy_ws(os.path.join(L, cws, "RocketFC"), os.path.join(L, f"rb_{cws}_{name}", "RocketFC"))
        if not os.path.exists(os.path.join(wb, ".regen")):
            subprocess.run([PY, os.path.join(wb, "tools", "burn_table.py"), *args], check=True,
                           cwd=wb, capture_output=True)
            open(os.path.join(wb, ".regen"), "w").write(" ".join(args))
        if not os.path.exists(os.path.join(wc, ".regen")):
            subprocess.run([PY, os.path.join(wc, "tools", "landing_table.py"), *args, *cgen],
                           check=True, cwd=wc, capture_output=True)
            open(os.path.join(wc, ".regen"), "w").write(" ".join(args))
        lit = f"{val}f"
        b = mc(wb, os.path.join(L, "data", f"rob_base_{name}.json"), fw={const: lit})
        c = mc(wc, os.path.join(L, "data", f"rob_{finalist}_{name}.json"), fw=dict(fw_cand, **{const: lit}))
        rows.append((name, *verdict(b, c)))
        print(fmt(rows[-1]), flush=True)
    for name, plant in PLANT:
        b = mc(os.path.join(L, "ws_base", "RocketFC"), os.path.join(L, "data", f"rob_base_{name}.json"), plant=plant)
        c = mc(os.path.join(L, cws, "RocketFC"), os.path.join(L, "data", f"rob_{finalist}_{name}.json"),
               fw=fw_cand, plant=plant)
        rows.append((name, *verdict(b, c)))
        print(fmt(rows[-1]), flush=True)
    allok = all(r[1] for r in rows)
    print(f"ROBUSTNESS GATE ({finalist}): {'PASS' if allok else 'FAIL'}")
    with open(os.path.join(L, "data", f"robustness_{finalist}.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(fmt(r) for r in rows) + f"\nGATE: {'PASS' if allok else 'FAIL'}\n")


def fmt(r):
    name, ok, sb, sc, p = r
    ab = lambda s: ",".join(f"{k[:4]}{v}" for k, v in sorted(s["aborts"].items()))
    return (f"{name:16s} {'ok ' if ok else 'BAD'} table med {sb['median']:5.2f} p90 {sb['p90']:5.2f} hops {sb['hops']:3d} [{ab(sb)}] | "
            f"cand med {sc['median']:5.2f} p90 {sc['p90']:5.2f} hops {sc['hops']:3d} [{ab(sc)}] | "
            f"dMed {p['d_median']:+.2f} [{p['d_median_ci'][0]:+.2f},{p['d_median_ci'][1]:+.2f}] "
            f"dP90 {p['d_p90']:+.2f} [{p['d_p90_ci'][0]:+.2f},{p['d_p90_ci'][1]:+.2f}]")


if __name__ == "__main__":
    main()
